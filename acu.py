def ref(*codes):
    """把穴位代码展开成带名称与归经的引用，供前端生成链接。"""
    out = []
    for c in codes:
        p = PBY.get(c)
        if not p:
            continue
        out.append(dict(code=c, name=p['name'], mer=MNO[p['mer']]['short'] if p['mer'] in MNO else p['mer'],
                        mer_no=p['mer'] if p['mer'] in MNO else 0,
                        loc=p['loc'], special=p['special'], act=p['act']))
    return out


